"""FEAT-GTS-261: writes a placeholder library's C source and module definition from its export list.

  python generate.py <list.nids> <output.c> <output.def>

Each line of the list is "<library> <NID>": a function GT Sport or GT7 imports that RyGTS does not implement.
The library exports one function per NID that reports "[stub] <library> <NID>" on its first call and
returns 0. A library with an empty list exports only ryty_stub_none: the game loads it at start but
calls nothing in it. See README.md.

FEAT-GTS-291: one build serves both games, so a line may end in "gt7=<value>": under GT7 that function
returns <value> (a 32-bit hex or decimal number) instead of 0. The game is told apart as the runtime
does (core/libs/GameSerial.hpp): SHADGT_GAME=gt7 or gts/gtsport, else GT7.exe is GT7.

FIX-RT-003: a line may end in "wait=timeval" instead: the function's first argument points to a PS4
timeval (64-bit seconds, 64-bit microseconds) and it sleeps that long, at most 100 ms, before
returning 0. GT7's USB event thread calls sceUsbdHandleEventsTimeout in a loop; on a PS4 the call
waits for an event or the timeout, and a placeholder that returned at once spun one core all session.
"""
import re
import sys
from pathlib import Path

ENTRY = re.compile(r'^(lib[A-Za-z0-9_\-]+) ([A-Za-z0-9+\-]{11})'
                   r'(?: gt7=(0x[0-9A-Fa-f]{1,8}|[0-9]+)| (wait=timeval))?$')

# The running game, read once: SHADGT_GAME as the launcher sets it, else the executable's name.
GAME_CHECK = r'''static volatile LONG game_known; /* 0: not read yet, 1: GT Sport, 2: GT7 */
static int running_gt7(void) {
    LONG known = game_known;
    if (known == 0) {
        char game[16];
        DWORD length = GetEnvironmentVariableA("SHADGT_GAME", game, sizeof(game));
        int gt7 = 0, set = 0;
        if (length > 0 && length < sizeof(game)) {
            if (lstrcmpiA(game, "gt7") == 0) { gt7 = 1; set = 1; }
            else if (lstrcmpiA(game, "gts") == 0 || lstrcmpiA(game, "gtsport") == 0) set = 1;
        }
        if (!set) {
            wchar_t path[MAX_PATH * 2];
            DWORD size = GetModuleFileNameW(NULL, path, MAX_PATH * 2);
            if (size > 0 && size < MAX_PATH * 2) {
                const wchar_t* name = path;
                for (const wchar_t* c = path; *c; ++c) if (*c == L'\\' || *c == L'/') name = c + 1;
                gt7 = lstrcmpiW(name, L"GT7.exe") == 0;
            }
        }
        known = gt7 ? 2 : 1;
        InterlockedExchange(&game_known, known);
    }
    return known == 2;
}'''


# FIX-RT-019: conversions can import these SaveData functions through libSceMbus.
# Match the provider signatures in prx/libSceSaveData/Export.cpp, including its guest ABI.
# Structures are opaque here; only the provider reads their contents.
SAVE_DATA_ARGUMENTS = {
    '0z45PIH+SNI': 'const void* mount, void* result',  # Mount2
    '85zul--eGXs': 'const void* mount, uint32_t type, const void* data, size_t size',  # SetParam
    'BMR4F-Uek3E': 'const void* mount',  # Umount
    'RQOqDbk3bSU': 'const void* check',  # CheckBackupData
    'S1GkePI17zQ': 'const void* request',  # Delete
    'VwadwBBBJ80': 'const void* mount',  # UmountWithBackup
    'XgvSuIdnMlw': 'const void* mount, uint32_t type, void* data, size_t size, size_t* read',  # GetParam
    'c88Yy54Mx0w': 'const void* mount, const void* icon',  # SaveIcon
    'dyIhnXq-0SM': 'const void* query, void* result',  # DirNameSearch
    'lU9YRFsgwSU': 'const void* restore',  # RestoreBackupData
}


def save_data_forwarder(index, nid):
    signature = SAVE_DATA_ARGUMENTS[nid]
    arguments = ', '.join(param.rsplit(' ', 1)[1] for param in signature.split(', '))
    return f'''__attribute__((sysv_abi)) int s{index}({signature}) {{
    typedef __attribute__((sysv_abi)) int (*Provider)({signature});
    HMODULE module = GetModuleHandleW(L"libSceSaveData.prx");
    Provider call = module ? (Provider)GetProcAddress(module, "{nid}") : NULL;
    if (call) return call({arguments});
    note({index});
    return (int32_t)0x809F000Bu; /* SCE_SAVE_DATA_ERROR_INTERNAL */
}}'''


def main(listing, source, definition):
    library = Path(listing).stem
    entries = []
    for number, line in enumerate(Path(listing).read_text(encoding='ascii').splitlines(), 1):
        match = ENTRY.match(line)
        if not match:
            sys.exit(f'{listing}:{number}: expected "<library> <NID>", "<library> <NID> gt7=<value>" '
                     'or "<library> <NID> wait=timeval"')
        owner, nid, gt7, wait = match.groups()
        value = int(gt7, 0) if gt7 is not None else None
        if value is not None and value > 0xFFFFFFFF:
            sys.exit(f'{listing}:{number}: gt7= is a 32-bit value')
        entries.append((owner, nid, value, wait is not None))
    nids = [nid for _, nid, _, _ in entries]
    if len(set(nids)) != len(nids):
        sys.exit(f'{listing}: a NID is listed twice')
    lines = ['/* Generated by core/libs/placeholders/generate.py from ' + library + '.nids; do not edit. */',
             '#include <stdint.h>', '#include <stdio.h>', '#include <windows.h>', '']
    if entries:
        lines.append(f'static volatile LONG seen[{len(entries)}];')
        lines.append('static const char* const names[] = {' +
                     ','.join('"' + owner + ' ' + nid + '"' for owner, nid, _, _ in entries) + '};')
        lines.append('static void note(int i) { if (!InterlockedExchange(&seen[i], 1)) { fputs("[stub] ", stderr); '
                     'fputs(names[i], stderr); fputc(10, stderr); fflush(stderr); } }')
        if any(value is not None for _, _, value, _ in entries):
            lines.append(GAME_CHECK)
        for i, (owner, nid, value, wait) in enumerate(entries):
            if library == 'libSceMbus' and owner == 'libSceSaveData':
                lines.append(save_data_forwarder(i, nid))
                continue
            if wait:
                # FIX-RT-003: waits as the real call does for its timeout (at most 100 ms), no events.
                lines.append(f'__attribute__((sysv_abi)) int64_t s{i}(const int64_t* tv) {{ note({i}); '
                             'int64_t ms = 100; if (tv) { ms = tv[0] * 1000 + tv[1] / 1000; '
                             'if (ms < 1) ms = 1; if (ms > 100) ms = 100; } Sleep((DWORD)ms); return 0; }')
                continue
            result = '(int32_t)0' if value is None else f'running_gt7() ? (int32_t)0x{value:X}u : (int32_t)0'
            lines.append(f'__attribute__((sysv_abi)) int64_t s{i}(void) {{ note({i}); return {result}; }}')
    else:
        lines.append('__attribute__((sysv_abi)) int64_t ryty_stub_none(void) { return 0; }')
    Path(source).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    exports = [f'  "{nid}"=s{i}' for i, (_, nid, _, _) in enumerate(entries)] or ['  ryty_stub_none']
    Path(definition).write_text('\n'.join([f'LIBRARY {library}.prx', 'EXPORTS'] + exports) + '\n',
                                encoding='ascii', newline='\n')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
